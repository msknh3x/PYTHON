# storing text in string
username = "cyber_ninja"

# find the no of characters in the string
username_length = len(username)

# convert the string to uppercase
uppercase_name = username.upper()

# convert the string to lowercase
lowercase_name = username.lower()

# display the results
print("username:", username)
print("Length:", username_length)
print("Uppercase:", uppercase_name)
print("Lowercase:", lowercase_name)