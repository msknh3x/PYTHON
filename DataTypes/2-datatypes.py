# string
name = "Muskan"
print("Name:", name)

# integer
age = 19
print("Age:", age)

# float
height = 5.4
print("Height:", height)

# Boolean
is_student = True
print("Is_Student:", is_student)

# list
fruits = ["apple", "mango", "orange"]
print("Fruits:", fruits)

# dictionary -> stores data in key-value pair
student = {
    "name": "Muskan",
    "age": 19,
    "is_student" : True
}
print("Student Info:", student)

student = {
   "name": "Muskan",
   "age": 19,
   "is_student" : True
}
print(student["name"])
print(student["age"])
print(student["is_student"])
